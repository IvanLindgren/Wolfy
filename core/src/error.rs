//! Ошибки ядра.
//!
//! Через границу FFI паника не выпускается, поэтому всё, что может пойти не
//! так, возвращается значением. Битая книга — это `Err`, а не падение
//! приложения: читатель должен увидеть «файл повреждён» и вернуться в
//! библиотеку.

use std::fmt;

/// Результат операции ядра.
pub type Result<T> = std::result::Result<T, CoreError>;

/// Что могло пойти не так внутри ядра.
#[derive(Debug, thiserror::Error)]
pub enum CoreError {
    /// Файл книги не читается: нет прав, нет файла, оборвался поток.
    #[error("не удалось прочитать файл: {0}")]
    Io(#[from] std::io::Error),

    /// Файл прочитан, но это не та книга, за которую себя выдаёт: сломанный
    /// архив EPUB, отсутствующий манифест, неизвестная разметка.
    #[error("книга повреждена или не поддерживается: {0}")]
    Malformed(String),

    /// Встроенный лексикон не разобрался. Случай особый: файл собирается
    /// генератором и едет внутри бинарника, поэтому такая ошибка означает
    /// битую сборку, а не проблему пользователя.
    #[error("лексикон повреждён: {0}")]
    Lexicon(String),
}

impl CoreError {
    /// Числовой код для FFI: на той стороне нет типов Rust, есть только int.
    pub fn code(&self) -> i32 {
        match self {
            CoreError::Io(_) => 1,
            CoreError::Malformed(_) => 2,
            CoreError::Lexicon(_) => 3,
        }
    }
}

/// Короткое описание для отладочных логов клиента.
impl CoreError {
    pub fn describe(&self) -> String {
        fmt::format(format_args!("{self}"))
    }
}
