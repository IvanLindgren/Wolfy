//! Как читается страница: якорь слова и отрезок чтения.
//!
//! Оба правила лингвистические или текстовые, поэтому живут здесь, а не в
//! интерфейсе: якорь считается по словарю и морфологии, отрезок — по границам
//! предложений. Интерфейсу остаётся показать результат.
//!
//! Модуль отвечает за *подачу* текста, а не за его разбор: он не решает, что
//! слово значит, — только где у него граница основы и докуда честно читать
//! за один подход.

