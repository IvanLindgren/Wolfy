/// Что движок нашёл в предложении.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Finding {
    /// Устойчивое имя правила: `present-perfect`, `passive-voice`. По нему
    /// клиент открывает справку и связывает разбор с упражнениями.
    pub rule: &'static str,
    /// Название для человека: «Present Perfect».
    pub title: &'static str,
    /// Схема формулы: «have/has + V3». Стоит рядом с объяснением всегда —
    /// правило без формулы не запоминается.
    pub formula: &'static str,
    /// Объяснение по-человечески: «действие уже случилось, и важен результат,
    /// а не когда именно». Живёт рядом с правилом, а не в интерфейсе: одно и
    /// то же правило обязано объясняться одинаково везде.
    pub explanation: String,
    /// Слова предложения, к которым относится разбор.
    pub words: Range<usize>,
    /// Те же слова в индексах токенов — по ним клиент подсвечивает страницу.
    pub tokens: Range<usize>,
}

impl Finding {
    /// Собирает разбор, переводя индексы слов в индексы токенов.
    ///
    /// Перевод делается здесь, а не на клиенте: слова — внутреннее устройство
    /// разбора, и знать о нём снаружи незачем.
    pub(crate) fn new(
        rule: &'static str,
        title: &'static str,
        formula: &'static str,
        explanation: impl Into<String>,
        words: &[Word],
        range: Range<usize>,
    ) -> Finding {
        let tokens = token_range(words, &range);
        Finding {
            rule,
            title,
            formula,
            explanation: explanation.into(),
            words: range,
            tokens,
        }
    }
}

/// Индексы токенов, занятых этими словами.
fn token_range(words: &[Word], range: &Range<usize>) -> Range<usize> {
    let start = words.get(range.start).map(|w| w.token).unwrap_or(0);
    let end = range
        .end
        .checked_sub(1)
        .and_then(|i| words.get(i))
        .map(|w| w.token + 1)
        .unwrap_or(start);
    start..end
}

/// Детектор одного правила.
type Detector = fn(&[Word]) -> Vec<Finding>;

/// Реестр. Порядок задаётся здесь и только здесь — сами детекторы о нём не
/// знают и знать не должны.
///
/// Он совпадает с порядком, в котором правила осваивает человек: сначала
/// времена и залог, затем модальные, затем неличные формы, затем условные.
/// Это не техническое требование, а забота о читателе: разборы одного
/// предложения показываются в этом же порядке, и первым он видит главное.
const DETECTORS: [Detector; 5] = [
    tense::detect,
    passive::detect,
    modal::detect,
    verbal::detect,
    conditional::detect,
];

/// Разбирает предложение.
///
/// На вход идут токены целого предложения: разбор смотрит на соседей, и
/// обрывок фразы разберётся хуже, чем фраза целиком.
pub fn analyze(lexicon: &Lexicon, tokens: &[Token]) -> Vec<Finding> {
    let words = tag(lexicon, tokens);
    analyze_words(&words)
}

/// То же, но по уже размеченному предложению — размётка стоит дороже разбора,
/// и повторять её ради второго вопроса о том же предложении незачем.
pub fn analyze_words(words: &[Word]) -> Vec<Finding> {
    DETECTORS.iter().flat_map(|detect| detect(words)).collect()
}
