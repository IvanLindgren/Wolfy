//! Грамматический разбор предложения.
//!
//! Движок объясняет читателю, что происходит во фразе: какое время, какой
//! залог, зачем здесь модальный глагол, почему условие выглядит так странно.
//! Он детерминирован — одно и то же предложение всегда разбирается одинаково,
//! иначе читатель перестаёт доверять разбору, а доверие здесь и есть продукт.
//!
//! ## Устройство
//!
//! Одно правило — один детектор — один файл. Детекторы не знают друг о друге и
//! не выстроены в конвейер: каждый смотрит на размеченное предложение сам и
//! отвечает за себя. Поэтому «is read» даёт сразу два разбора — время от
//! одного детектора и залог от другого, — и ни один из них не пришлось учить
//! второму.
//!
//! Общий у них только фундамент: [`chain`] находит группу сказуемого и
//! раскладывает её на звенья. Он не детектор и ничего не объясняет.
//!
//! ## Об осторожности
//!
//! Ложное срабатывание хуже пропуска. Читатель, увидевший неверный разбор,
//! перестаёт верить и верному, а пропущенное правило он просто не заметит.
//! Поэтому у каждого детектора есть не только примеры, которые обязаны
//! сработать, но и близкие к ним — которые сработать не должны.
//!
//! Правила слоя — в `rules/grammar_engine.md`.

