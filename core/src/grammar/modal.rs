//! Модальные глаголы: «can», «must», «should», «might».
//!
//! Времени они не образуют — потому их и не разбирает детектор времён. Они
//! говорят об отношении к действию: возможно оно, обязательно, желательно или
//! всего лишь вероятно.
//!
//! Почти каждый из них значит два разных вещи, и выбрать между ними по форме
//! нельзя: «must» это и «обязан», и «наверняка», «may» — и «можно», и «вдруг».
//! Разница держится на смысле, а не на грамматике, поэтому объяснение называет
//! оба значения вместо того, чтобы угадывать. Есть, впрочем, один надёжный
//! признак: модальный глагол с третьей формой («must have left») почти всегда
//! говорит о догадке про прошлое, а не о долге.

use crate::tagger::Word;

use super::chain::{chains, Link};
use super::Finding;

pub fn detect(words: &[Word]) -> Vec<Finding> {
    chains(words)
        .iter()
        .filter_map(|chain| {
            let head = chain.head()?;
            if head.link != Link::Modal {
                return None;
            }
            let modal = words.get(head.word)?;

            // «will» и «shall» здесь не разбираются: они образуют будущее
            // время, и говорит о них детектор времён. Разобрать их дважды
            // значило бы показать читателю два ответа на один вопрос.
            if matches!(modal.lower.as_str(), "will" | "shall") {
                return None;
            }

            // Модальный с третьей формой говорит о прошлом, и это отдельное
            // правило: «he must have left» не про обязанность.
            if chain.is_perfect() {
                return Some(Finding::new(
                    "modal-perfect",
                    "Модальный глагол о прошлом",
                    "модальный + have + V3",
                    explain_perfect(&modal.lower),
                    words,
                    chain.words.clone(),
                ));
            }

            Some(Finding::new(
                "modal-verb",
                "Модальный глагол",
                "модальный + V",
                explain(&modal.lower),
                words,
                chain.words.clone(),
            ))
        })
        .collect()
}

/// Объяснение для модального с третьей формой.
///
/// Все они говорят о прошлом, но говорят разное, и общая формулировка про
/// «догадку» врала бы на половине примеров: «should have» это упрёк, а не
/// догадка, «would have» — несбывшееся, а не предположение.
fn explain_perfect(modal: &str) -> &'static str {
    match modal {
        "must" => "Уверенная догадка о прошлом: иначе быть не могло",
        "may" | "might" | "could" => "Предположение о прошлом: возможно, так и было",
        "should" | "ought" => "Упрёк или сожаление: следовало сделать, но сделано не было",
        "would" => "Несбывшееся: это случилось бы, но условие не выполнилось",
        "can" => "Сомнение в том, что это вообще было",
        _ => "Оценка того, что уже произошло, а не самого действия",
    }
}

fn explain(modal: &str) -> &'static str {
    match modal {
        "can" => "Умение или возможность: «умеет» и «в состоянии»",
        "could" => "Умение в прошлом или вежливая просьба — а ещё осторожное «мог бы»",
        "may" => "Разрешение или вероятность: «можно» и «может быть»",
        "might" => "Вероятность, но меньшая, чем у «may»: скорее «вдруг», чем «может быть»",
        "must" => "Обязанность или уверенность: «должен» и «наверняка»",
        "should" | "ought" => "Совет: так будет правильно, но никто не заставляет",
        "would" => "Условность или вежливость: «бы» и «не могли бы вы»",
        _ => "Отношение говорящего к действию: возможно оно, нужно или всего лишь вероятно",
    }
}
