-- Реестр устройств для сборки мусора заметок.
--
-- Пометка удаления стирается, только когда каждое устройство, у которого
-- могла остаться копия этой книги, подтвердило, что долговечно сохранило
-- состояние с версией не ниже пометки. Здесь хранится это подтверждение:
-- максимум номера версии, о котором устройство отчиталось серверу.
--
-- Устройство регистрируется первым же обращением за заметками книги —
-- и чтением, и записью: держатель копии обязан блокировать сборку мусора
-- независимо от того, пишет он или только читает. Устройство, которое
-- никогда не обращалось, копии не имеет и в реестре не числится.
CREATE TABLE wolfy.book_annotations_devices (
    user_id   uuid   NOT NULL,
    book_id   text   NOT NULL,
    device_id text   NOT NULL,
    seen_rev  bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (user_id, book_id, device_id)
);
