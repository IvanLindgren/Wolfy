-- Реестр устройств для сборки мусора заметок.
--
-- Пометка удаления стирается, только когда каждое устройство, у которого
-- могла остаться копия этой книги, подтвердило, что долговечно сохранило
-- снимок поколения не ниже пометки. Здесь хранится это подтверждение:
-- наибольшее поколение, о котором устройство отчиталось серверу.
--
-- Устройство регистрируется первым же обращением за заметками книги —
-- и чтением, и записью: держатель копии обязан блокировать сборку мусора
-- независимо от того, пишет он или только читает. Устройство, которое
-- никогда не обращалось, копии не имеет и в реестре не числится.
--
-- Строки не удаляются по возрасту намеренно: устройство, пропавшее на
-- полгода, держит копию, и единственный честный способ учесть его —
-- оставить его подтверждение в замороженном виде. Строка — десятки байт,
-- и растут они только от реальных устройств, поэтому плата за звучание
-- сборки — копеечная. Исключение сюда однажды добавит протокол «устройство
-- само отписало книгу», но не таймер.
CREATE TABLE wolfy.book_annotations_devices (
    user_id        uuid   NOT NULL,
    book_id        text   NOT NULL,
    device_id      text   NOT NULL,
    seen_generation bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (user_id, book_id, device_id)
);
