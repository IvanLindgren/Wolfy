-- Дозапись поколений снимков в базы, созданные до правки 0003 и 0004.
--
-- Обе те миграции однажды поправили на месте, уже после того как они
-- применились в production: 0003 дописала колонку generation, а 0004
-- переименовала seen_rev в seen_generation. Журнал миграций помнит только имя
-- файла, поэтому изменённый файл второй раз не выполняется. Свежая база берёт
-- новую редакцию и выглядит правильной - на ней и проходят все тесты, - а
-- production остался со схемой прежней версии, тогда как код с тех пор пишет
-- по новой. Наружу это вышло много позже и совсем в другом месте:
-- ERROR: column "generation" does not exist при перепривязке книги.
--
-- Здесь то же изменение сделано как положено, отдельной миграцией и с
-- проверками: на свежей базе всё уже создано файлами 0003 и 0004, и каждый шаг
-- ничего не делает.
ALTER TABLE wolfy.book_annotations
    ADD COLUMN IF NOT EXISTS generation bigint NOT NULL DEFAULT 0;

-- Переименование и сброс идут вместе и только на старой схеме.
--
-- Сброс подтверждений в ноль здесь не осторожность, а условие правильности.
-- seen_rev хранил номер правки писателя: счётчик Лампорта, который рос от
-- каждой правки на устройстве и к этому моменту у живых читателей далеко не
-- нулевой. Поколение выдаёт сервер, и в production оно начнётся с нуля.
-- Оставить старые числа под новым именем значило бы, что MIN(seen_generation)
-- сразу больше поколения любой новой пометки удаления: первое же слияние
-- стёрло бы пометку, не дождавшись ни одного устройства, и удалённая заметка
-- вернулась бы с той машины, которая удаления не видела.
--
-- Ноль ничего не теряет. Он лишь откладывает сборку пометок до следующей
-- синхронизации каждого устройства, а устройство поднимает своё подтверждение
-- само, первым же обращением за заметками книги.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
         WHERE table_schema = 'wolfy'
           AND table_name   = 'book_annotations_devices'
           AND column_name  = 'seen_rev'
    ) THEN
        ALTER TABLE wolfy.book_annotations_devices
            RENAME COLUMN seen_rev TO seen_generation;
        UPDATE wolfy.book_annotations_devices SET seen_generation = 0;
    END IF;
END $$;

-- Страховка на случай базы, где нет ни того, ни другого имени.
ALTER TABLE wolfy.book_annotations_devices
    ADD COLUMN IF NOT EXISTS seen_generation bigint NOT NULL DEFAULT 0;
