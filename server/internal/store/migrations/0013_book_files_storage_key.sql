-- Где лежат байты книги, отдельно от того, чьи они.
--
-- Путь к файлу собирался из номера книги: <корень>/<читатель>/<книга>.book.
-- Пока номер книги неизменен, разницы нет, но он изменяем: при совпадении
-- source_key синхронизация переводит книгу на канонический номер и
-- перепривязывает к нему карточки, заметки и устройства. Файл при этом не
-- переносился никуда, потому что перенести его одной транзакцией нельзя -
-- переименование на диске не откатится вместе с ней. Книга оставалась без
-- серверной копии: второе устройство её не находило, а старый файл лежал
-- мёртвым грузом под номером, которого больше нет.
--
-- storage_key разрывает эту связь. Номер книги остаётся тем, чей это файл, а
-- storage_key - тем, где он лежит. Перепривязка теперь меняет только
-- book_id, обычной строкой внутри той же транзакции, и файл никуда не едет.
--
-- Тип тот же uuid: старые файлы уже названы номерами книг, и заполнение ниже
-- лишь записывает в новую колонку то, что и так было правдой.
ALTER TABLE wolfy.book_files
    ADD COLUMN IF NOT EXISTS storage_key uuid;

UPDATE wolfy.book_files SET storage_key = book_id WHERE storage_key IS NULL;

ALTER TABLE wolfy.book_files
    ALTER COLUMN storage_key SET NOT NULL;
