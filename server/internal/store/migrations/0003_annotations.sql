-- Заметки и выделения к книгам.
--
-- Одна строка на пару «читатель — книга»: внутри jsonb лежит весь список
-- отметок. Цитаты — куски книги, но хранятся они здесь, а не рядом с книгой:
-- сама книга живёт файлом на устройстве и на сервер не попадает, а отметка —
-- её тень, которая как раз и обязана переезжать между устройствами.
--
-- Слияние делает сервер по правилу «у записи новее время правки — та и
-- верна». Поэтому два устройства, писавшие в одну книгу одновременно,
-- теряют заметки друг друга, только если правили одну и ту же запись в одну
-- и ту же секунду; удаление доезжает до всех как пометка, а не как пропажа.
CREATE TABLE wolfy.book_annotations (
    user_id    uuid        NOT NULL,
    book_id    text        NOT NULL,
    items      jsonb       NOT NULL DEFAULT '[]'::jsonb,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, book_id)
);
