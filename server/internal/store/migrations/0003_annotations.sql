-- Заметки и выделения к книгам.
--
-- Одна строка на пару «читатель — книга»: внутри jsonb лежит весь список
-- отметок. Цитаты — куски книги, но хранятся они здесь, а не рядом с книгой:
-- сама книга живёт файлом на устройстве и на сервер не попадает, а отметка —
-- её тень, которая как раз и обязана переезжать между устройствами.
--
-- Конфликт версий решает пара (rev, writer): номер правки в счётчике
-- Лампорта писателя и его стабильный номер устройства. Часы устройств врут,
-- а (rev, writer) — полный детерминированный порядок.
--
-- Сборка мусора пометок удалений работает по поколениям снимка (generation),
-- которые выдаёт только сервер: каждое изменившее состояние слияние
-- увеличивает поколение и штампует им все записи. Устройство подтверждает,
-- что долговечно сохранило снимок поколения G, и пометка стирается, когда
-- каждое зарегистрированное устройство подтвердило поколение не ниже её.
-- Возраст в сборке не участвует: у пролежавшего в ящике устройства осталась
-- старая копия, и только подтверждение, а не календарь, говорит, что её
-- больше нет.
CREATE TABLE wolfy.book_annotations (
    user_id    uuid        NOT NULL,
    book_id    text        NOT NULL,
    items      jsonb       NOT NULL DEFAULT '[]'::jsonb,
    generation bigint      NOT NULL DEFAULT 0,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, book_id)
);
