package com.wolfy.theme

import androidx.compose.ui.graphics.Color

/**
 * Краски маркера.
 *
 * Значения взяты из веба (`theme/theme.css`, переменные `--hl-*`) один в один.
 * Это не педантизм: отметки синхронизируются между устройствами, и жёлтое
 * выделение, сделанное в браузере, обязано остаться жёлтым на телефоне. Краска
 * едет числом, а не цветом, поэтому единственное, что держит их вместе, -
 * одинаковая таблица на обоих концах.
 *
 * Тона одни на все четыре темы. Пастель на тёмной бумаге выглядит ярче, чем на
 * светлой, но подмешивать к ней фон значило бы, что одна и та же отметка
 * называется разным цветом в разных темах, - а читатель помнит свои краски по
 * цвету, не по номеру. Читаемость держит [highlightInk]: поверх светлой
 * заливки текст всегда тёмный.
 */
private val HIGHLIGHTS = listOf(
    Color(0xFFFFE9A3), // 1 жёлтый
    Color(0xFFFFD3A8), // 2 оранжевый
    Color(0xFFFFC9D4), // 3 розовый
    Color(0xFFFFBDB5), // 4 красный
    Color(0xFFE3D0F5), // 5 фиолетовый
    Color(0xFFC5DBF5), // 6 синий
    Color(0xFFBFE8EF), // 7 голубой
    Color(0xFFC8E6C0), // 8 зелёный
    Color(0xFFE2E3AE), // 9 оливковый
    Color(0xFFDCDCD5), // 10 серый
)

/** Цвет краски по её номеру. Незнакомый номер получает серый. */
fun highlightColor(tone: Int): Color =
    HIGHLIGHTS.getOrElse(tone - 1) { HIGHLIGHTS.last() }

/**
 * Чернила поверх краски.
 *
 * Заливки светлые всегда, поэтому текст на них всегда тёмный - включая тёмные
 * темы, где обычные чернила светлые. Без этого выделенное слово на ночной теме
 * становилось бы светлым по светлому, то есть невидимым ровно там, куда
 * читатель нарочно поставил метку.
 */
val HighlightInk: Color = Color(0xFF1A1A1A)
