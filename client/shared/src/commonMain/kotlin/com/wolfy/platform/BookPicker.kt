package com.wolfy.platform

import androidx.compose.runtime.Composable

/** Книга, которую пользователь выбрал в системном окне. */
data class PickedBook(
    /** Путь к читаемому файлу. Может быть временной копией. */
    val path: String,
    /** Имя, под которым файл показывать и хранить. */
    val name: String,
)

/**
 * Выбор книги системным окном.
 *
 * Возвращает функцию, которая это окно открывает, — а не открывает его сама:
 * на Android запуск чужого экрана требует регистрации ещё до того, как его
 * позовут, и сделать это можно только внутри композиции.
 *
 * Форматы ограничены теми, что понимает ядро. Показывать пользователю все
 * файлы подряд, чтобы потом сказать «этот я не открою», — значит тратить его
 * время дважды.
 */
@Composable
expect fun rememberBookPicker(onPicked: (PickedBook) -> Unit): () -> Unit
