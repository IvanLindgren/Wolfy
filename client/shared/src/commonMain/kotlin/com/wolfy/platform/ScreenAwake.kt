package com.wolfy.platform

import androidx.compose.runtime.Composable

/**
 * Не даёт экрану погаснуть, пока открыта книга.
 *
 * Чтение — единственное занятие в приложении, за которым экрана не касаются
 * минутами: страница романа читается дольше, чем стоит любой разумный
 * системный таймер, и экран гаснет ровно посреди абзаца. Дальше читатель
 * тычет в стекло, попадает по слову, открывает карточку — и возвращается не
 * туда, где был.
 *
 * Зовётся из самой читалки и живёт, пока живёт её композиция: вышли из книги —
 * запрет снят. Обещать это на всё приложение нельзя, иначе телефон, забытый на
 * экране колод, не уснёт до утра.
 */
@Composable
expect fun KeepScreenAwake()
