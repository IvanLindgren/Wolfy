package com.wolfy.platform

import androidx.compose.runtime.Composable

/**
 * Напоминание о повторении.
 *
 * Момент считает ядро на Rust — по той же кривой
 * забывания, по которой назначены сроки карточек. Здесь остаётся только
 * донести его до системы, а система на Android и на Windows разная.
 *
 * Уведомление одно и всегда одно: следующее заменяет предыдущее. Очередь
 * напоминаний о том, что и так лежит в одном списке, — верный способ
 * добиться, чтобы уведомления выключили совсем.
 *
 * @param at когда показать, в миллисекундах эпохи.
 * @param count сколько карточек будет ждать к этому моменту — из него
 *   собирается текст, и ради него же напоминание вообще имеет смысл: «пора
 *   повторить» без числа ничего не сообщает.
 */
expect fun scheduleReviewReminder(at: Long, count: Int)

/** Снимает запланированное напоминание: повторять больше нечего. */
expect fun cancelReviewReminder()

/**
 * Готовит запрос разрешения на уведомления.
 *
 * Возвращает то, что нужно позвать в подходящий момент, а не спрашивает сразу:
 * системный диалог показывают один раз за установку, и потратить его на
 * первый запуск — значит не получить разрешения никогда.
 */
@Composable
expect fun rememberReminderPermission(): () -> Unit
