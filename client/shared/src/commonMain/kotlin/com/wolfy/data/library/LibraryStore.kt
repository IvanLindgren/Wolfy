package com.wolfy.data.library

/**
 * Хранилище приложения на устройстве.
 *
 * Отделено от [Library] намеренно: правила библиотеки одни и те же везде, а
 * место, куда всё это ложится, у Android и Windows разное. Интерфейс узкий —
 * ровно четыре действия, — и потому его легко подменить в тестах на память.
 *
 * Записи различаются именем, а не отдельным хранилищем на каждую: библиотека и
 * настройки живут в одном каталоге и отличаются только файлом. Заводить ради
 * второй записи вторую реализацию значило бы дважды написать одно и то же.
 *
 * Формат хранения — JSON, а не база. Библиотека это сотни записей, а не сотни
 * тысяч: база дала бы индексы, которые тут некуда применить, и миграции,
 * которые пришлось бы писать при каждом новом поле. Файл целиком читается за
 * миллисекунды и переживает любое изменение модели, потому что незнакомые поля
 * разбор пропускает.
 */
interface LibraryStore {
    /** Сохранённая запись или `null`, если её ещё нет. */
    fun load(name: String): String?

    /** Записывает. Обязана быть атомарной: обрыв записи не должен оставить
     *  пользователя без списка книг. */
    fun save(name: String, json: String)

    /**
     * Копирует книгу в хранилище приложения и возвращает путь к копии.
     *
     * Копия обязательна. На Android выбранный файл приходит ссылкой, которая
     * перестаёт работать после перезапуска, а на Windows пользователь вправе
     * удалить исходник — и книга, которую он читает, исчезнет вместе с ним.
     */
    fun importBook(sourcePath: String, fileName: String): String

    /** Удаляет файл книги. Записи в библиотеке это не касается. */
    fun deleteBook(path: String)

    /**
     * Отпечаток содержимого файла.
     *
     * По нему один и тот же файл, добавленный на телефоне и на компьютере,
     * узнаётся как одна книга. Имя для этого не годится: «book.epub» бывает у
     * чего угодно, а «Гэтсби (1).epub» — у того же самого.
     *
     * Пустая строка означает, что отпечаток снять не удалось: файл мог
     * исчезнуть между выбором и чтением. Это не ошибка — книга просто не
     * узнается автоматически.
     */
    fun fingerprint(path: String): String

    /** Текст книги из хранилища. Пустая строка — файла нет. */
    fun readText(path: String): String

    /**
     * Пишет текстовую книгу и возвращает путь к ней.
     *
     * Нужно распознанным страницам: они приходят текстом, а не файлом, и
     * копировать неоткуда. Существующий файл переписывается — снимки
     * накапливаются в одной книге.
     */
    fun writeText(fileName: String, text: String): String

    /**
     * Дописывает текстовую книгу, не перечитывая её целиком.
     *
     * Нужен OCR-снимкам: размер уже собранной книги не должен превращать
     * добавление одной страницы в O(total book size).
     */
    fun appendText(fileName: String, text: String): String

    /** Сохраняет загруженный EPUB без промежуточного файла платформы. */
    fun writeBook(fileName: String, bytes: ByteArray): String

    // --- обложки ---
    //
    // Обложка — украшение конкретного устройства, а не часть книги: файл
    // книги живёт своими путями на каждом устройстве, и путь к картинке
    // синхронизировать было бы нечем. Поэтому обложки лежат рядом с книгами,
    // но в библиотеку ядра не попадают вовсе.

    /**
     * Пишет обложку книги, заменяя прежнюю, и возвращает путь к ней.
     *
     * Одна книга — одна обложка: новая запись стирает старую, иначе после
     * третьей смены обложки каталог превратится в свалку картинок.
     */
    fun writeCover(bookId: String, extension: String, bytes: ByteArray): String

    /** Путь к обложке книги или `null`, если своей обложки у неё нет. */
    fun findCover(bookId: String): String?

    /** Стирает обложку книги. Отсутствующей не считается ошибкой. */
    fun deleteCover(bookId: String)

    /** Байты файла из хранилища. `null` — файла нет или он не читается. */
    fun readBinary(path: String): ByteArray?

    /** Путь к установленному офлайн-словарю или пустая строка. */
    fun dictionaryPath(): String

    /** Атомарно распаковывает скачанный словарь и возвращает его путь. */
    fun installDictionary(compressed: ByteArray): String
}

/** Хранилище для текущей платформы. */
expect fun createLibraryStore(): LibraryStore

/**
 * Архив словаря, вложенный в приложение.
 *
 * Он нужен не как второй источник истины, а как гарантированный первый
 * запуск: установленное приложение не должно зависеть от сервера разработчика
 * на localhost. Сервер остаётся способом обновить архив в будущих версиях.
 */
expect fun readBundledDictionary(): ByteArray?
