package com.wolfy.data.library

import kotlinx.serialization.Serializable

/**
 * Книга в библиотеке пользователя.
 *
 * Хранится отдельно от самого файла книги и переживает его переоткрытие: файл
 * ядро разбирает заново при каждом запуске, а прогресс, колода и полка — это
 * то, что пользователь накопил, и терять его нельзя.
 *
 * Идентификатор придумывает устройство, а не сервер, и он обязан быть UUID:
 * книга получает номер до того, как впервые дойдёт до сети, иначе её нельзя
 * добавить в самолёте, а на сервере под этот номер отведена колонка uuid.
 */
@Serializable
data class LibraryBook(
    /** Устойчивый номер книги: переживает перенос файла и синхронизацию. */
    val id: String,
    /**
     * Файл внутри хранилища приложения.
     *
     * Пустой путь — книга известна по синхронизации, но файла на этом
     * устройстве нет. Такое бывает всегда: сервер хранит, что вы читаете, но
     * не сами книги — книга пользователя это его файл.
     */
    val path: String = "",
    val title: String,
    val author: String? = null,
    /** `epub`, `txt`, `pdf` — по нему видно, чем книга была. */
    val format: String = "",
    /**
     * Отпечаток содержимого файла.
     *
     * По нему один и тот же файл, добавленный на телефоне и на компьютере,
     * узнаётся как одна книга, а не превращается в две с одинаковым названием.
     */
    val sourceKey: String = "",
    /** Когда книгу добавили — по нему библиотека сортируется. */
    val addedAt: Long = 0,
    /** Сколько глав нашло ядро. Ноль значит, что книгу ещё не открывали. */
    val chapters: Int = 0,
    val progress: Progress = Progress(),
    /** Название полки, на которой стоит книга. `null` — книга не разобрана. */
    val shelf: String? = null,

    /** Ревизия сервера, с которой запись согласована. Ноль — ни разу. */
    val rev: Long = 0,
    /** Изменена на этом устройстве и ещё не отправлена. */
    val dirty: Boolean = true,
    /**
     * Удалена.
     *
     * Запись остаётся с пометкой, а не стирается: стёртую второе устройство не
     * заметит, и книга там воскреснет.
     */
    val deleted: Boolean = false,
) {
    // Ниже — не правила, а проекции уже лежащих в записи чисел: их держат
    // здесь, потому что список книг спрашивает долю прочитанного у каждой
    // строки при каждом кадре, и ходить за этим через границу было бы
    // расточительством. Всё, что можно посчитать двумя способами и получить
    // разное — сроки, слияние, отбор в колоду, — живёт в ядре.

    /** Прочитанная доля от нуля до единицы. */
    val fraction: Float
        get() = when {
            chapters <= 0 -> 0f
            else -> ((progress.chapter + progress.withinChapter) / chapters).coerceIn(0f, 1f)
        }

    /** Открывали ли книгу хоть раз. */
    val started: Boolean get() = progress.openedAt > 0

    val finished: Boolean get() = fraction >= 0.999f

    /** Можно ли книгу открыть на этом устройстве. */
    val readable: Boolean get() = path.isNotBlank()
}

/**
 * Где пользователь остановился.
 *
 * Глава и доля внутри неё, а не общий процент: процент пришлось бы
 * пересчитывать при каждом изменении разбивки на главы, а глава с долей
 * переживает и смену версии ядра, и перенос книги на другое устройство.
 */
@Serializable
data class Progress(
    val chapter: Int = 0,
    /** Доля прочитанного внутри главы, от нуля до единицы. */
    val withinChapter: Float = 0f,
    /**
     * Стабильный якорь: индекс блока, с которого начинался видимый экран.
     *
     * Доля внутри главы зависит от высоты блоков и кегля, блок же — та же
     * структура, по которой читалка раскладывает страницу. Минус единица —
     * «якоря нет», позиция восстанавливается по старой доле. Так записи из
     * прежних версий не теряют своё место.
     */
    val blockIndex: Int = -1,
    /** Смещение внутри блока-якоря как доля его прокручиваемой высоты. */
    val blockOffset: Float = 0f,
    /** Когда книгу открывали в последний раз. Ноль — ни разу. */
    val openedAt: Long = 0,
)

/**
 * Слово или фраза в колоде.
 *
 * Карточка принадлежит книге, а не общему словарю. Так её и заводят: слова из
 * «Гэтсби» вспоминаются вместе с «Гэтсби», и повторять их вперемешку со
 * словами из учебника — значит лишить их единственной зацепки, которая есть.
 *
 * Поля повторений заполнены значениями по умолчанию: механика ещё впереди, но
 * место под неё есть и на сервере, и здесь — иначе первая же тренировка
 * потребовала бы миграции и у той, и у другой стороны.
 */
@Serializable
data class Card(
    val id: String,
    /** Книга, из которой слово пришло. Пусто — карточка из общей колоды. */
    val bookId: String = "",
    /**
     * Что за карточка: `word`, `phrase` или `rule`.
     *
     * Три колоды хаба повторений различаются только этим полем. Отдельных
     * типов нет намеренно: прочность, срок и серия у них одни и те же, а
     * разные типы заставили бы синхронизацию, хранилище и расписание знать
     * про каждый.
     */
    val kind: String = "word",
    /** Слово так, как оно стояло в тексте. */
    val surface: String,
    /** Начальная форма: по ней слово узнаётся при следующей встрече. */
    val lemma: String,
    val translation: String = "",
    /** Предложение, в котором слово встретилось: без него перевод не проверить. */
    val context: String = "",
    val pos: String = "",
    val cefr: String = "",

    /**
     * «Очки здоровья» карточки.
     *
     * Падают, когда слово уверенно узнают, и растут при ошибке. Карточка
     * с нулём считается выученной — так задумана механика повторений.
     */
    val hp: Int = 100,
    val streak: Int = 0,
    val intervalDays: Int = 0,
    /** Когда карточку показать снова, в миллисекундах эпохи. */
    val dueAt: Long = 0,
    val reviewedAt: Long = 0,
    val addedAt: Long = 0,

    val rev: Long = 0,
    val dirty: Boolean = true,
    val deleted: Boolean = false,
)

/**
 * Полка — способ разложить книги по своему усмотрению.
 *
 * Полка это имя и ничего больше. Своего номера у неё нет намеренно: книга
 * хранит название полки, и потому полки разъезжаются между устройствами сами,
 * вместе с книгами, без отдельной таблицы и отдельной синхронизации.
 *
 * Список полок нужен только ради пустых: полка, на которой пока ничего не
 * стоит, из книг не выводится, а завести её заранее — обычное дело.
 */
@Serializable
data class Shelf(
    val name: String,
    val createdAt: Long = 0,
)

/** Всё, что библиотека хранит между запусками. */
@Serializable
data class LibraryState(
    val books: List<LibraryBook> = emptyList(),
    val cards: List<Card> = emptyList(),
    val shelves: List<Shelf> = emptyList(),
    /**
     * Ревизия сервера, по которую состояние согласовано.
     *
     * Ноль — синхронизации ещё не было. Именно этот номер уходит на сервер
     * как «покажи всё, что новее».
     */
    val cursor: Long = 0,
    /** Локальный счётчик изменений — по нему видно, что писать на диск. */
    val revision: Long = 0,
) {
    /** Карточки книги, кроме удалённых. */
    fun deck(bookId: String): List<Card> =
        cards.filter { it.bookId == bookId && !it.deleted }

    /** Книги, которые видит пользователь. */
    val visible: List<LibraryBook> get() = books.filter { !it.deleted }
}
