package com.wolfy.data

/**
 * Перевод момента времени между сервером и устройством.
 *
 * Сервер говорит на RFC 3339 — так время выглядит в Postgres и в Go, и менять
 * это ради клиента было бы неправильно: формат читается глазами в логах и в
 * базе, а миллисекунды эпохи — нет. Устройство же хранит миллисекунды, потому
 * что сравнивать и сортировать числа проще, чем строки.
 *
 * Перевод живёт здесь и только здесь, чтобы никто больше не разбирал даты
 * руками.
 */
expect fun parseInstant(text: String): Long

/** Обратно: миллисекунды в RFC 3339. Ноль превращается в пустую строку. */
expect fun formatInstant(millis: Long): String

/**
 * Местный день как число.
 *
 * Серия дней считается по календарю читателя, а не по эпохе: «вчера
 * позанимался, сегодня позанимался» — это про полночь там, где он живёт.
 */
expect fun localDay(millis: Long): Long

/** Час местного времени, 0..23. */
expect fun localHour(millis: Long): Int

/**
 * Ближайший наступающий местный час, не раньше `from`.
 *
 * Нужен уведомлениям: напоминание, выпавшее на четыре утра, читателя не
 * порадует, и его сдвигают к утру.
 */
expect fun atLocalHour(from: Long, hour: Int): Long
