package com.wolfy.data

import com.wolfy.data.library.LibraryBook

/**
 * Строка, которой книга зовёт читателя обратно.
 *
 * Показывается там, где приложения нет на экране: в виджете на рабочем столе
 * Android и в панели на рабочем столе Windows. Задача у неё одна — напомнить,
 * что книга открыта на середине, и дать вернуться в неё одним нажатием.
 *
 * Почему не «пора почитать». Напоминание, которое требует, работает ровно
 * один раз, после чего его выключают. Работает другое — незаконченность:
 * человек возвращается не потому, что должен, а потому что интересно, чем там
 * кончилось. Поэтому в строке всегда стоит название книги, место в ней и одна
 * фраза, которая ничего не требует.
 *
 * Фраза выбирается по дню и по книге, а не случайно при каждой отрисовке:
 * виджет перерисовывается системой когда ей вздумается, и подмигивающий
 * разными фразами прямоугольник на рабочем столе — это не приглашение, а
 * мельтешение.
 */
data class BookNudge(
    /** «Вас ждёт книга: Дракула». */
    val title: String,
    /** «Вы остановились на 41-й странице из 320». */
    val place: String,
    /** Фраза дня — та, что ничего не требует. */
    val teaser: String,
) {
    /** Одной строкой — для подсказки в трее, где нет места на три. */
    fun oneLine(): String = listOf(title, place, teaser).filter { it.isNotBlank() }.joinToString(" ")
}

/**
 * Фразы-приглашения.
 *
 * Ни одна не обещает того, чего мы не знаем: «возможно», «кажется», «где-то
 * там». Утверждать «вас ждёт поворот сюжета» нельзя — мы не читали эту книгу
 * и не знаем, ждёт ли.
 */
private val TEASERS = listOf(
    "Возможно, вас ждёт сюжетный поворот.",
    "Страница, на которой вы остановились, всё ещё открыта.",
    "Кажется, там кто-то не договорил.",
    "Полчаса — и станет ясно, чем всё кончилось.",
    "Книга не ушла никуда.",
    "Где-то там осталась незакрытая мысль.",
    "Пара страниц — тоже чтение.",
    "Слова из неё ждут в колоде.",
    "Вы были на самом интересном месте. Или почти.",
    "Продолжение — там же, где вы его оставили.",
)

/**
 * Собирает приглашение к книге.
 *
 * `day` — номер местного дня; по нему выбирается фраза. Передаётся снаружи,
 * потому что часы и часовой пояс — платформенные, а эта функция должна
 * оставаться проверяемой.
 *
 * `null` означает «звать некуда»: библиотека пуста или ни одна книга не
 * открыта. Показывать в этом случае «пора почитать» нельзя — читать нечего.
 */
fun bookNudge(book: LibraryBook?, day: Long): BookNudge? {
    if (book == null || book.deleted) return null

    val title = book.title.trim().ifBlank { "ваша книга" }
    // Ключ фразы — день и книга: в один день у одной книги фраза одна и та же,
    // а у двух разных книг — разные.
    val index = ((day + title.hashCode().toLong()).mod(TEASERS.size.toLong())).toInt()

    return BookNudge(
        title = "Вас ждёт книга: $title",
        place = placeOf(book),
        teaser = TEASERS[index],
    )
}

/**
 * Где читатель остановился.
 *
 * Долей, а не страницей: страница зависит от кегля и ширины экрана, и число,
 * верное на телефоне, окажется неверным на компьютере. Доля верна везде.
 *
 * У книги, которую ещё не открывали, места нет — и придумывать его не надо:
 * «вы остановились на 0%» звучит как упрёк.
 */
private fun placeOf(book: LibraryBook): String {
    if (!book.started) return "Вы её ещё не открывали."

    // Доля считается там же, где её считает список книг: два способа однажды
    // разошлись бы, и виджет показывал бы не то, что полка.
    val percent = (book.fraction * 100).toInt().coerceIn(0, 100)
    return when {
        percent <= 0 -> "Вы её ещё не открывали."
        percent >= 99 -> "Осталась последняя страница."
        else -> "Вы остановились на $percent%."
    }
}
