package com.wolfy.ui.card

/**
 * Цитата, готовая к тому, чтобы её куда-нибудь вставили.
 *
 * Зачем вообще. Фраза из книги нужна читателю не только в колоде: её
 * пересылают, кладут в свои заметки, приводят в разговоре. До сих пор
 * единственным способом было переписать её с экрана руками — при том, что
 * приложение держит и само предложение, и его перевод.
 *
 * Форма — та, которой цитату записывают от руки: сама фраза в кавычках, под
 * ней перевод. Ёлочки, а не лапки: текст русский, и в русском наборе цитата
 * оформляется так.
 *
 * Перевод не дожидаемся. Он приезжает из сети и может не приехать вовсе, а
 * копирование обязано работать без сети — фраза-то уже на экране. Пришёл
 * позже — попадёт в следующую копию.
 */
fun quoteOf(sentence: String, translation: String): String {
    val text = sentence.trim()
    if (text.isEmpty()) return ""
    val russian = translation.trim()
    val quoted = "«$text»"
    return if (russian.isEmpty()) quoted else "$quoted\n$russian"
}
