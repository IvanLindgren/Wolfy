package com.wolfy.widgets

/**
 * Геометрия буквицы: во сколько её набрать и куда поставить.
 *
 * Вынесено из вёрстки отдельно, потому что вся ошибка буквицы всегда живёт
 * здесь, в трёх числах, а не в расстановке `Placeable`. Проверить их
 * раскладкой нельзя — Compose не отдаёт наружу ни высоту литеры, ни её верх, —
 * а арифметику проверить можно, и она проверяется тестом.
 *
 * ## От чего считается высота
 *
 * Буквица в N строк — это литера, у которой **верх стоит на линии прописных
 * первой строки, а низ — на базовой линии N-й**. Обе границы принадлежат
 * набору, а не коробке абзаца.
 *
 * Прежний код брал верхнюю границу у коробки: высота литеры отсчитывалась от
 * верха первой строки, то есть включала и междустрочный воздух, и надстрочное
 * поле шрифта. У читалки это около семи точек при кегле 19 — литера выходила
 * примерно на десятую часть выше, чем ей полагается, и стояла над текстом
 * отдельным этажом вместо того, чтобы начинаться с ним вровень.
 */
/**
 * Вёрстка берёт отсюда только [fontSize]: посадкой литеры на базовую линию
 * занимается сама раскладка, а не число. [inkTop] и [inkHeight] — то же
 * правило, записанное явно; по ним его и проверяют.
 */
internal data class DropCapPlan(
    /** Кегль, которым набирается литера. */
    val fontSize: Float,
    /** Отступ верха литеры от верха абзаца. Никогда не отрицательный. */
    val inkTop: Float,
    /** Высота самой литеры: от линии прописных до базовой линии N-й строки. */
    val inkHeight: Float,
)

/**
 * @param bodyBaseline первая базовая линия набора, замером, а не формулой.
 * @param bodyCapHeight высота прописной буквы набора: доля кегля из шрифта.
 * @param lineHeight межстрочный интервал набора.
 * @param lines сколько строк занимает буквица.
 * @param capHeightRatio доля кегля, которую занимает прописная в шрифте буквицы.
 */
internal fun dropCapPlan(
    bodyBaseline: Float,
    bodyCapHeight: Float,
    lineHeight: Float,
    lines: Int,
    capHeightRatio: Float,
): DropCapPlan {
    val rows = (lines - 1).coerceAtLeast(0)
    val inkHeight = bodyCapHeight + lineHeight * rows
    // Верх литеры совпадает с верхом прописных первой строки. Ниже нуля он
    // опуститься не может по построению, но кегль читалки задаёт читатель, и
    // отрицательная координата от чужого шрифта здесь стоила бы литеры,
    // залезшей на конец прошлого абзаца.
    val inkTop = (bodyBaseline - bodyCapHeight).coerceAtLeast(0f)
    return DropCapPlan(
        fontSize = inkHeight / capHeightRatio,
        inkTop = inkTop,
        inkHeight = inkHeight,
    )
}

/**
 * Есть ли эта буква во Fraunces.
 *
 * Fraunces — латинская антиква и только: в её `cmap` нет ни кириллицы, ни
 * греческого. Русская глава начиналась буквицей, которую рисовал случайный
 * системный шрифт, а кегль ей при этом считали по метрике Fraunces — отсюда и
 * литера не той высоты, и не тот характер там, где характер и был весь смысл.
 *
 * Граница — конец латиницы расширенной B (U+024F). Дальше во Fraunces идут
 * только диакритика и знаки, а буквой абзац начинается всё равно.
 */
internal fun frauncesHasLetter(letter: Char): Boolean = letter.code <= 0x024F
