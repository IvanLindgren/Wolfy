package com.wolfy.srs

/**
 * Интенсивность повторений.
 *
 * Один и тот же материал можно проходить за месяц и за неделю — разница в
 * том, сколько времени читатель готов тратить каждый день. Выбор его, а не
 * приложения: «экстрим» перед экзаменом и «лёгкий» на каникулах — это один
 * человек в разные недели, а не два разных пользователя.
 *
 * Здесь остались только надписи. На что именно интенсивность влияет —
 * насколько растягиваются сроки и со скольких забытых слов приходит
 * напоминание — знает ядро на Rust, и знает в одном месте: иначе телефон и
 * настольная машина назначили бы одному и тому же слову разные сроки.
 *
 * Имена совпадают с теми, что понимает ядро, и уезжают на сервер как есть:
 * переименовать элемент в коде можно, а переименовать `Strong` в чужой
 * базе — уже нет.
 */
enum class Intensity(
    val title: String,
    /** Чем режим отличается — строкой, которую видно под переключателем. */
    val hint: String,
) {
    Gentle("Лёгкий", "спокойно, без давления"),
    Normal("Средний", "по умолчанию"),
    Strong("Сильный", "чаще, чтобы запоминать быстрее"),
    Extreme("Экстрим", "почти каждый день");

    companion object {
        /** По имени. Незнакомое — средняя: она подходит всем. */
        fun of(name: String): Intensity = entries.firstOrNull { it.name == name } ?: Normal
    }
}
