package com.wolfy.platform

import androidx.compose.runtime.Composable

/**
 * На Windows напоминаний нет — и это осознанно, а не «пока не сделали».
 *
 * Напоминание имеет смысл там, где устройство всегда с человеком и умеет его
 * окликнуть. Настольное приложение окликнуть читателя не может: оно закрыто,
 * когда он не за столом, а когда открыто — он и так его видит. Уведомление в
 * трее закрытого приложения не показать, а держать ради этого фоновую службу
 * значит просить у человека постоянно работающий процесс ради одной строки
 * текста.
 *
 * Расписание при этом общее: карточки, созревшие на компьютере, приезжают
 * синхронизацией на телефон, и напомнит о них он.
 */
actual fun scheduleReviewReminder(at: Long, count: Int) = Unit

actual fun cancelReviewReminder() = Unit

@Composable
actual fun rememberReminderPermission(): () -> Unit = {}
