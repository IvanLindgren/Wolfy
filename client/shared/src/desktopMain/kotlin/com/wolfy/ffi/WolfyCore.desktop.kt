package com.wolfy.ffi

/**
 * Ядро на Windows.
 *
 * Путь к библиотеке задаёт сборка через `-Djna.library.path`: при запуске из
 * исходников это каталог, куда её положила задача `copyCoreLibrary`, а в
 * установленном приложении она лежит рядом с исполняемым файлом и находится
 * системным поиском. Искать её из кода не нужно — иначе получилось бы два
 * источника правды о том, где лежит ядро.
 *
 * Экземпляр один на приложение: ядро держит внутри разобранный словарь на
 * семьдесят восемь тысяч слов, и загружать его дважды значило бы удвоить
 * расход памяти на ровном месте.
 */
private val core: WolfyCore by lazy { loadCore() }

actual fun createWolfyCore(): WolfyCore = core
