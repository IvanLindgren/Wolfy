/**
 * Единый темп всех осмысленных движений интерфейса.
 *
 * Один модуль на всё приложение — как `theme/Motion.kt` в клиенте. Смысл в
 * том, что «меньше движения» заменяет **весь объект** нулями, и ни один экран
 * не знает об этой настройке отдельно. Иначе про неё забудут в двадцатом по
 * счёту виджете, и читатель, попросивший тишины, получит десять анимаций из
 * одиннадцати.
 *
 * Длительности — миллисекунды, потому что так их принимает CSS и так они
 * записаны в клиенте. `motion/react` хочет секунды, и перевод делает
 * [`seconds`], а не каждый вызов на месте.
 */

export interface Motion {
  /** Нажатие, переключение таблетки. */
  instant: number
  /** Появление мелочи, смена подписи. */
  quick: number
  /** Выезд карточки, переход экрана. */
  calm: number
  /** Полёт слова в колоду, тасование. */
  flight: number
  /** Задержка между элементами каскада. */
  stagger: number
}

export const motion: Motion = {
  instant: 90,
  quick: 180,
  calm: 280,
  flight: 560,
  stagger: 40,
}

/** Всё стоит на месте. Содержимое при этом остаётся на экране. */
export const noMotion: Motion = {
  instant: 0,
  quick: 0,
  calm: 0,
  flight: 0,
  stagger: 0,
}

/**
 * Кривые. Их ровно две, и у каждой своя работа.
 *
 * `paper` — появление и переходы: быстрый старт, долгое успокоение, как лист
 * бумаги, ложащийся на стол. `toss` — бросок карточки в колоду: почти без
 * разгона в начале и с резкой остановкой, как брошенный предмет.
 */
export const curves = {
  paper: [0.22, 0.61, 0.36, 1] as const,
  toss: [0.35, 0.0, 0.1, 1] as const,
}

export const curveCss = {
  paper: 'cubic-bezier(0.22, 0.61, 0.36, 1)',
  toss: 'cubic-bezier(0.35, 0, 0.1, 1)',
}

/** Длительность в секундах — в таких единицах их принимает `motion/react`. */
export function seconds(ms: number): number {
  return ms / 1000
}

/**
 * Просит ли система убрать движение.
 *
 * Системная настройка и настройка приложения складываются: любая из двух
 * означает тишину. Читатель, включивший «меньше движения» в системе, не
 * обязан повторять это в каждом приложении.
 */
export function systemPrefersReducedMotion(): boolean {
  if (typeof window === 'undefined' || !window.matchMedia) return false
  return window.matchMedia('(prefers-reduced-motion: reduce)').matches
}
